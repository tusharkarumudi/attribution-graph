def _disclosed_hostname() -> str:
    """Workstation hostname, only if explicitly disclosed.

    Evidence packages are built to be shared, and the manifest recorded the
    local hostname and $USER by default. That is useful for internal chain of
    custody and a privacy leak everywhere else, in a system that otherwise
    emphasises minimisation.

    Opt in with EAE_DISCLOSE_HOST=1 when the package stays internal.
    """

    if os.environ.get("EAE_DISCLOSE_HOST") not in ("1", "true", "yes"):
        return "(not disclosed)"
    return socket.gethostname()


def _disclosed_operator() -> str:
    """Operator identity. Declared, not inferred from $USER."""

    return os.environ.get("EAE_OPERATOR") or "(not disclosed)"


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


#: Top-level manifest fields bound by the envelope digest. Listed explicitly
#: rather than "everything except the digest", so adding a field is a decision
#: someone makes rather than a silent widening.
ENVELOPE_FIELDS = (
    "schema", "case_ref", "authorization", "opened_at", "closed_at",
    "capture_count", "manifest_hash", "environment", "fetch_policy",
    "outcomes", "notice", "retention_expiry",
)


def envelope_digest_of(doc: dict) -> str:
    """Canonical digest over ENVELOPE_FIELDS. Same function for writer and
    verifier, so the two cannot drift."""
    import json as _json

    payload = {
        "envelope_schema": doc.get("envelope_schema", "manifest/1"),
        **{k: doc.get(k) for k in ENVELOPE_FIELDS},
    }
    return hashlib.sha256(
        _json.dumps(payload, sort_keys=True, separators=(",", ":"),
                    default=str).encode()).hexdigest()


#: Case material is sensitive by the project's own documentation, so it is not
#: written at whatever the ambient umask happens to be. An empirical probe
#: found 0755 directories and 0644 files: on a shared host or CI runner, any
#: local user could read captured content, investigation URLs and case
#: metadata.
SECURE_DIR_MODE = 0o700
SECURE_FILE_MODE = 0o600


def secure_mkdir(path) -> None:
    """Create a directory 0700, and tighten it if it already exists."""
    from pathlib import Path as _P

    p = _P(path)
    p.mkdir(parents=True, exist_ok=True, mode=SECURE_DIR_MODE)
    # Tighten an existing directory too: mode= only applies at creation, and a
    # pre-existing 0755 output directory is exactly the shared-host case.
    with contextlib.suppress(OSError):
        p.chmod(SECURE_DIR_MODE)


def secure_write(path, data) -> None:
    """Write a file 0600, creating parents 0700.

    The mode is applied before the content: creating world-readable and then
    tightening leaves a window in which the data is exposed.
    """
    import os
    from pathlib import Path as _P

    p = _P(path)
    secure_mkdir(p.parent)
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    fd = os.open(p, flags, SECURE_FILE_MODE)
    try:
        with os.fdopen(fd, "wb" if isinstance(data, bytes) else "w") as fh:
            fh.write(data)
    finally:
        with contextlib.suppress(OSError):
            p.chmod(SECURE_FILE_MODE)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


