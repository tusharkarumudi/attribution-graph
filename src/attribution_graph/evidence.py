"""Evidence preservation and chain of custody.

A report describing what a tool found is not evidence. It is a summary of
evidence that no longer exists, because the web changed the moment after you
looked.

The central point, which most investigative tooling gets wrong: **live web
findings are not reproducible.** You cannot re-run a query in 2028 and get 2026's
answer, and any "reproducible steps" section that implies otherwise is
misleading. What survives is the *preserved response body* captured at a known
time with a verifiable hash. The steps explain how the conclusion was reached;
the capture is what proves the input existed.

So this module records four things per fetch:

1. The exact request (URL, method, headers sent, timestamp in UTC)
2. The exact response (status, headers, body) written to disk unmodified
3. A SHA-256 over the raw body, and a manifest hash chaining every capture
4. Who or what performed it, under which case authorization

Plus the thing analysts forget: **negative results**. "We queried Companies
House for this name on this date and it returned nothing" is evidentially
meaningful and is unrecoverable later.

## On admissibility

This module produces the technical substrate. It does not make anything
admissible, and nothing here is legal advice.

In US federal practice the relevant rules are FRE 901(b)(9) (evidence describing
a process or system, showing it produces an accurate result) and FRE 902(13)–(14)
(self-authenticating certified records generated by an electronic process, and
certified data copied from an electronic device, each requiring a certification
from a qualified person). ``declaration_template()`` emits a skeleton for that
certification. Other jurisdictions differ substantially — England and Wales,
India's certificate regime for electronic records (Bharatiya Sakshya
Adhiniyam 2023, s.63 -- formerly Evidence Act s.65B), and EU member states
each impose
different requirements. Counsel decides what is needed; this gives them
something to work with.

One caution worth stating plainly: the confidence scores this toolkit produces
are opinion, not observation. Offering them in proceedings likely engages expert
evidence standards (FRE 702 / Daubert in the US), and the calibration gap
documented in METHOD.md §7 is directly relevant to whether they would survive
that scrutiny. Present captures as fact and scores as analysis, and do not let a
report blur the two.
"""

