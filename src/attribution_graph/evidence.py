@dataclass
class Capture:
    """One request/response pair, preserved."""

    url: str
    method: str
    requested_at: datetime
    status: int | None
    body_sha256: str
    body_bytes: int
    body_path: str
    request_headers: dict[str, str] = field(default_factory=dict)
    response_headers: dict[str, str] = field(default_factory=dict)
    collector: str = ""
    outcome: str = "success"          # success | empty | error | refused
    note: str = ""
    #: Which vantage point served this capture. Part of the hashed envelope
    #: because a capture attributed to the wrong exit is a false record.
    egress: str = ""
    sequence: int = 0
    prev_hash: str = ""
    entry_hash: str = ""

    #: Bumped whenever the hashed field set changes, so a package produced by
    #: an older version cannot be silently verified under newer rules.
    ENTRY_SCHEMA = "capture/2"

    def compute_entry_hash(self) -> str:
        """Hash every integrity-relevant field, not only body identity.

        Version 1 hashed sequence, URL, method, timestamp, status, body digest
        and previous hash. It did **not** hash request headers, response
        headers, collector, note or body_path -- so it was possible to rewrite
        all four on a real package and have the standalone verifier report
        PASSED. "Verified" did not mean the provenance was unaltered, which is
        the one thing an evidence package exists to establish.

        The envelope is versioned and sorted so a future field cannot fall
        outside it by omission: adding a field without bumping ENTRY_SCHEMA
        changes the digest of every capture and fails loudly.
        """
        envelope = {
            "schema": self.ENTRY_SCHEMA,
            "sequence": self.sequence,
            "url": self.url,
            "method": self.method,
            "requested_at": self.requested_at.isoformat(),
            "status": self.status,
            "body_sha256": self.body_sha256,
            "body_bytes": self.body_bytes,
            "body_path": self.body_path,
            "collector": self.collector,
            "outcome": getattr(self.outcome, "value", str(self.outcome)),
            "note": self.note,
            "request_headers": dict(sorted((self.request_headers or {}).items())),
            "response_headers": dict(sorted((self.response_headers or {}).items())),
            "egress": self.egress,
            "prev_hash": self.prev_hash,
        }
        payload = json.dumps(envelope, sort_keys=True, separators=(",", ":"),
                             default=str)
        return hashlib.sha256(payload.encode()).hexdigest()

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["requested_at"] = self.requested_at.isoformat()
        return d


class EvidenceLog:
    """Append-only capture log with a hash chain and a manifest.

    Usage sits alongside the fetcher rather than inside it, so a collector that
    forgets to record is visibly missing from the manifest rather than silently
    unrecorded.
    """

    def __init__(self, scope: CaseScope, root: Path) -> None:
        self.scope = scope
        self.root = Path(root)
        self.bodies = self.root / "captures"
        self.bodies.mkdir(parents=True, exist_ok=True)
        self.captures: list[Capture] = []
        self.opened_at = _utcnow()
        self._last_hash = ""
        #: Populated by the caller from PolicyEngine.summary(). Recorded so the
        #: package can state what the collection policy was, not merely what it
        #: collected.
        self.fetch_policy: dict | None = None

    # ---- recording -------------------------------------------------------- #

    def record(
        self,
        url: str,
        status: int | None,
        body: bytes | str | None,
        *,
        method: str = "GET",
        request_headers: dict[str, str] | None = None,
        response_headers: dict[str, str] | None = None,
        collector: str = "",
        outcome: str | None = None,
        note: str = "",
        requested_at: datetime | None = None,
        egress: str = "",
    ) -> Capture:
        raw = b"" if body is None else (body.encode() if isinstance(body, str) else body)
        digest = sha256_bytes(raw)
        seq = len(self.captures) + 1

        # Content-addressed: identical bodies stored once, and the filename is
        # itself verifiable against the hash in the manifest.
        path = self.bodies / f"{digest}.bin"
        if not path.exists():
            secure_write(path, raw)

        if outcome is None:
            if status is None or status >= 400:
                outcome = "error"
            elif not raw:
                outcome = "empty"
            else:
                outcome = "success"

        cap = Capture(
            url=url,
            method=method,
            requested_at=requested_at or _utcnow(),
            status=status,
            body_sha256=digest,
            body_bytes=len(raw),
            body_path=str(path.relative_to(self.root)),
            request_headers=dict(request_headers or {}),
            response_headers=dict(response_headers or {}),
            collector=collector,
            outcome=outcome,
            note=note,
            sequence=seq,
            prev_hash=self._last_hash,
            egress=egress,
        )
        cap.entry_hash = cap.compute_entry_hash()
        self._last_hash = cap.entry_hash
        self.captures.append(cap)
        return cap

    def record_negative(
        self, url: str, collector: str, note: str, *, status: int | None = 200
    ) -> Capture:
        """A query that ran and returned nothing.

        Evidentially meaningful and unrecoverable later. "We searched the
        register on this date and it held no matching entity" is a finding.
        """
        return self.record(url, status, b"", collector=collector,
                           outcome="empty", note=note)

    def record_refusal(self, target: str, collector: str, reason: str) -> Capture:
        """A source deliberately not queried.

        Recording what you chose not to do matters as much as what you did --
        it is the difference between a scoped investigation and one that simply
        failed to find something.
        """
        return self.record(target, None, b"", collector=collector,
                           outcome="refused", note=reason)

    # ---- verification ------------------------------------------------------ #

    def _safe_body_path(self, body_path: str) -> Path | None:
        """Resolve a manifest body_path, refusing anything outside the package.

        When verifying a package you did not create, the manifest is untrusted
        input and ``body_path`` is a file-read primitive: "../../../etc/shadow"
        resolves happily under a naive join.
        """
        candidate = (self.root / body_path).resolve()
        try:
            candidate.relative_to(self.root.resolve())
        except ValueError:
            return None
        return candidate

    def verify(self) -> tuple[bool, list[str]]:
        """Re-check every body hash and the full chain."""
        problems: list[str] = []
        prev = ""
        for cap in self.captures:
            p = self._safe_body_path(cap.body_path)
            if p is None:
                problems.append(
                    f"seq {cap.sequence}: body_path escapes the package "
                    f"({cap.body_path}) — the manifest is malformed or hostile")
                prev = cap.entry_hash
                continue
            if not p.exists():
                problems.append(f"seq {cap.sequence}: body missing ({cap.body_path})")
            elif sha256_bytes(p.read_bytes()) != cap.body_sha256:
                problems.append(f"seq {cap.sequence}: body hash mismatch")
            if cap.prev_hash != prev:
                problems.append(f"seq {cap.sequence}: chain break")
            if cap.compute_entry_hash() != cap.entry_hash:
                problems.append(f"seq {cap.sequence}: entry hash mismatch")
            prev = cap.entry_hash
        return (not problems), problems

    # ---- output ------------------------------------------------------------ #

    @property
    def manifest_hash(self) -> str:
        """The capture-chain head.

        Retained under its existing name so older packages still parse, but it
        is NOT the package digest: it commits only to the capture chain. See
        ``envelope_hash``.
        """
        return self._last_hash or sha256_bytes(b"")

    #: Bumped when the envelope's field set changes, so a package written by an
    #: older version cannot be silently verified under newer rules.
    ENVELOPE_SCHEMA = "manifest/1"

    def envelope_digest(self, doc: dict) -> str:
        """Digest over the top-level manifest metadata AND the chain head.

        The chain protects the captures. Nothing protected the manifest's own
        assertions, so editing ``case_ref``, ``authorization``,
        ``fetch_policy`` and ``environment.tool_version`` on a valid package
        and the official verifier still returned ok, reporting the forged case
        reference back.

        For an evidence-preservation tool those are the load-bearing claims:
        under what authority the collection happened, under what policy, and
        with which build. A verifier that authenticates the bytes but not the
        circumstances authenticates the wrong thing.
        """
        return envelope_digest_of(doc)

    def environment(self) -> dict[str, str]:
        from . import __version__
        return {
            "tool": "attribution-graph",
            "tool_version": __version__,
            "python": platform.python_version(),
            "platform": platform.platform(),
            "hostname": _disclosed_hostname(),
            "operator": _disclosed_operator(),
        }

    def write_manifest(self) -> Path:
        ok, problems = self.verify()
        doc = {
            "case_ref": self.scope.case_ref,
            "authorization": self.scope.authorization,
            "opened_at": self.opened_at.isoformat(),
            "closed_at": _utcnow().isoformat(),
            "environment": self.environment(),
            "capture_count": len(self.captures),
            "outcomes": {
                o: sum(1 for c in self.captures if c.outcome == o)
                for o in ("success", "empty", "error", "refused")
            },
            "fetch_policy": self.fetch_policy or {
                "robots_policy": self.scope.robots_policy,
                "statement": "Policy declared in the case file; per-URL "
                             "evaluation was not recorded for this run.",
            },
            "manifest_hash": self.manifest_hash,
            "self_verified": ok,
            "verification_problems": problems,
            "captures": [c.to_dict() for c in self.captures],
            "notice": (
                "Live web findings are not reproducible. Re-running these requests "
                "at a later date will not return the same content. The preserved "
                "bodies under captures/ are the evidentiary artifact; this manifest "
                "attests to what was retrieved, when, and that it is unaltered."
            ),
        }
        # Bind the top-level assertions. Without this, the chain authenticated
        # the captures while case_ref, authorization, fetch_policy and the tool
        # version could be rewritten freely and still verify.
        doc["envelope_schema"] = self.ENVELOPE_SCHEMA
        doc["envelope_digest"] = envelope_digest_of(doc)

        path = self.root / "evidence_manifest.json"
        secure_write(path, json.dumps(doc, indent=2, default=str))
        return path

    def write_timestamp_request(self) -> Path:
        """RFC 3161 timestamp request over the manifest hash.

        A hash chain proves internal consistency but not *when* it was made --
        the operator controls the clock. A trusted timestamp from a third-party
        TSA closes that gap and is what turns "we say we captured this in
        August" into something independently checkable.

            openssl ts -query -data evidence_manifest.json -sha256 -cert \\
                -out request.tsq
            curl -H "Content-Type: application/timestamp-query" \\
                --data-binary @request.tsq <TSA_URL> -o response.tsr
            openssl ts -verify -data evidence_manifest.json \\
                -in response.tsr -CAfile tsa-ca.pem
        """
        path = self.root / "TIMESTAMP.md"
        secure_write(path,
            "# Trusted timestamping\n\n"
            f"Manifest hash (SHA-256 chain head): `{self.manifest_hash}`\n\n"
            "The hash chain proves the capture set is internally consistent and "
            "unaltered. It does not prove *when* it was created, because the "
            "operator controls the system clock. Obtain an RFC 3161 timestamp "
            "from a trusted authority to close that gap:\n\n"
            "```bash\n"
            "openssl ts -query -data evidence_manifest.json -sha256 -cert -out request.tsq\n"
            "curl -H \"Content-Type: application/timestamp-query\" \\\n"
            "     --data-binary @request.tsq <TSA_URL> -o response.tsr\n"
            "openssl ts -verify -data evidence_manifest.json -in response.tsr \\\n"
            "     -CAfile tsa-ca.pem\n"
            "```\n\n"
            "Store `response.tsr` alongside the manifest. Do this at capture "
            "time; a timestamp obtained months later proves only that the file "
            "existed by then.\n"
        )
        return path


